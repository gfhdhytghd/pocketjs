/** Glyphs whose advance is not [`DEFAULT_ADVANCE`]. */
export const ADVANCE_OVERRIDE: Record<string, number> = {
  " ": 4,
  ".": 3,
  ",": 3,
  "!": 3,
  "'": 2,
  ":": 3,
  ";": 3,
  i: 4,
  l: 4,
  "1": 5,
};

/** The advance of one character. */
export function advanceOf(ch: string): number {
  return ADVANCE_OVERRIDE[ch] ?? DEFAULT_ADVANCE;
}

/** Every character the font carries, in a stable order. */
export function characters(): string[] {
  return Object.keys(FONT);
}

/**
 * Rasterize one glyph into an 8x8 cell of palette indices.
 *
 * The glyph sits at (0, 0) of the cell with its 7 rows top-aligned, so the
 * baseline is consistent and the core's line spacing is just the cell height.
 */
export function rasterize(ch: string, ink: number): Uint8Array {
  const cell = new Uint8Array(CELL * CELL); // 0 = transparent
  const glyph = FONT[ch];
  if (!glyph) return cell;
  for (let y = 0; y < GLYPH_H; y++) {
    const row = glyph[y] ?? "";
    for (let x = 0; x < GLYPH_W; x++) {
      if (row[x] === "#") cell[y * CELL + x] = ink;
    }
  }
  return cell;
}
