//
// Hand-authored rather than rasterized from a TTF. At this size a hinted
// outline font turns to mush, and the whole point of the runtime's look is
// that every pixel is deliberate. Rows are written as '#'/'.' so a glyph can
// be read and edited in place.
//
// Metrics: 5 px wide, 7 px tall, 6 px advance (5 + 1 of side bearing).
